CREATE DATABASE IF NOT EXISTS sehatiq CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sehatiq;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  pass VARCHAR(255) NOT NULL,
  theme VARCHAR(8) NOT NULL DEFAULT 'light',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS profiles (
  user_id INT PRIMARY KEY,
  nama VARCHAR(80), umur SMALLINT DEFAULT 25, jk CHAR(1) DEFAULT 'L',
  tinggi DECIMAL(5,1) DEFAULT 170, berat DECIMAL(5,1) DEFAULT 65, gol VARCHAR(2) DEFAULT 'O',
  alergi VARCHAR(255) DEFAULT '', kondisi VARCHAR(255) DEFAULT '', kontak VARCHAR(100) DEFAULT '', telp VARCHAR(30) DEFAULT '',
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS vitals (
  id CHAR(16) NOT NULL, user_id INT NOT NULL,
  `date` DATE, `time` VARCHAR(5), sys SMALLINT NULL, dia SMALLINT NULL, glu SMALLINT NULL, gctx VARCHAR(10) NULL,
  hr SMALLINT NULL, temp DECIMAL(4,1) NULL, spo2 SMALLINT NULL, bb DECIMAL(5,1) NULL, note VARCHAR(255),
  PRIMARY KEY (user_id,id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS meds (
  id CHAR(16) NOT NULL, user_id INT NOT NULL,
  nama VARCHAR(120), dosis VARCHAR(80), stok INT NULL, jam VARCHAR(120), cat VARCHAR(255),
  PRIMARY KEY (user_id,id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS med_log (
  user_id INT NOT NULL, log_key VARCHAR(80) NOT NULL,
  PRIMARY KEY (user_id,log_key), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS appts (
  id CHAR(16) NOT NULL, user_id INT NOT NULL,
  dokter VARCHAR(120), spes VARCHAR(60), tgl DATE, jam VARCHAR(5), lokasi VARCHAR(160), cat VARCHAR(255), selesai TINYINT DEFAULT 0,
  PRIMARY KEY (user_id,id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS records (
  id CHAR(16) NOT NULL, user_id INT NOT NULL,
  tipe VARCHAR(30), judul VARCHAR(160), tgl DATE, faskes VARCHAR(160), catatan TEXT,
  PRIMARY KEY (user_id,id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS journal (
  id CHAR(16) NOT NULL, user_id INT NOT NULL,
  tgl DATE, mood TINYINT, tidur DECIMAL(3,1), air SMALLINT, olah SMALLINT, cat TEXT,
  PRIMARY KEY (user_id,id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS chat (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, role CHAR(1), msg TEXT,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
